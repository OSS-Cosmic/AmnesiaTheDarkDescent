-- Link the engine + its full dependency set into a final executable. premake
-- does NOT transitively propagate a static library's links to consumers, so
-- every executable (Amnesia, editors, MshConverter) must link the whole set.
-- linkgroups handles the circular static-lib references (vorbis<->ogg, etc.).
function link_engine(target_layout, product)
    if type(target_layout) == "table" then
        product = target_layout.product or target_layout.context
        target_layout = target_layout.target_layout or target_layout.layout
    elseif product == nil and target_layout ~= nil and
        target_layout ~= "game" and target_layout ~= "tests" then
        -- A lone non-layout argument is the convenient product form:
        -- link_engine("tools") means a game-layout link for the tools runtime.
        product, target_layout = target_layout, "game"
    elseif product == "game" or product == "tests" then
        -- Also accept link_engine(product, target_layout).
        target_layout, product = product, target_layout
    end
    target_layout = target_layout or "game"
    product = runtime_context(product, target_layout)
    local dependency_product = target_layout == "tests" and "amnesia" or product
    -- AMFP links its own engine build; consumer TUs need the same define so
    -- they see the same class layouts as the library.
    local engine_lib, angelscript_lib = "HPL2", "AngelScript"
    if product == "amfp" then
        engine_lib, angelscript_lib = "HPL2_AMFP", "AngelScript_AMFP"
        defines { "AMFP" }
    end
    links {
        engine_lib, "OALWrapper", angelscript_lib, "Newton", "tinyxml2", "fmt",
        "vorbisfile", "vorbis", "ogg", "freealut",
        "zlib", "volk", "IL", "png", "jpeg",
    }
    if os.target() == "windows" and _OPTIONS["with-d3d12"] == "yes" then
        links { "D3D12MA" }
    end
    link_sdl2(dependency_product)
    link_openal(dependency_product)
    link_nrd(target_layout, dependency_product)
    link_fsr(target_layout, dependency_product)
    link_xess(target_layout, dependency_product)
    if target_layout == "tests" then
        link_test_runtime_rpath(dependency_product)
    end
    memory_consumer()
    memory_rebuild_consumer()
    filter "system:linux"
        links { "pthread", "dl" }
    filter "system:windows"
        -- Static SDL2/openal-soft do not bring their CMake target dependency
        -- lists with them, so final Windows executables link the Win32 libs here.
        links {
            "kernel32",
            "setupapi",
            "winmm",
            "imm32",
            "version",
            "cfgmgr32",
            "ole32",
            "oleaut32",
            "uuid",
            "advapi32",
            "user32",
            "gdi32",
            "shell32",
            "avrt",
            "dinput8",
        }
        if _OPTIONS["with-d3d12"] == "yes" then
            links { "d3d12", "dxgi", "dxguid" }
            link_agility_runtime(target_layout, product)
        end
        if _OPTIONS["with-tracy"] == "yes" then
            links { "ws2_32", "dbghelp" }   -- TracyClient (network + symbol resolution)
        end
    filter "toolset:gcc or clang"
        linkgroups "On"
    filter {}
end
